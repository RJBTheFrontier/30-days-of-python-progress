# Integer
print(10)
print(-5)

# Float
print(3.14)
print(0.5)

# Complex
print(1 + 3j)
print(2j)

# String
print("Hello, World!")
print("Python")

# Boolean
print(True)
print(False)

# List (Ordered and mutable collection)
print([1, 2, 3, 4, 5])
print(["Python", "Java", "C++"])

# Tuple (Ordered and immutable collection)
print((1, 2, 3, 4))
print(("Earth", "Mars", "Jupiter"))

# Set (Unordered and unindexed collection of unique items)
print({1, 2, 3, 4, 4, 5})  # Duplicates will automatically be removed

# Dictionary (Key-value pairs)
print({"name": "Asabeneh", "country": "Finland", "age": 250})


# Points: P1(2, 3) and P2(10, 8)
x1, y1 = 2, 3
x2, y2 = 10, 8

# Euclidean distance formula
distance = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5

print("The Euclidean distance is:", distance)
